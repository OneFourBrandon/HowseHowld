import { expect, test } from '@playwright/test'

test('opens own and roommate balance histories with payment filters', async ({ page }) => {
  await page.goto('/money')
  await page.getByRole('button', { name: 'View balance for Brandon' }).click()
  const dialog = page.getByRole('dialog', { name: "Brandon's balance" })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByText('Monthly rent', { exact: true }).first()).toBeVisible()
  await dialog.getByRole('button', { name: 'Payments', exact: true }).click()
  await expect(dialog.getByText('Received from Noah')).toHaveCount(0)
  await expect(dialog.getByText('pending', { exact: true })).toHaveCount(0)
  await expect(dialog.getByText('No non-zero payments yet.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'View balance for Noah' }).click()
  const other = page.getByRole('dialog', { name: "Noah's balance" })
  await other.getByRole('button', { name: 'Payments', exact: true }).click()
  await expect(other.getByText('Sent to Brandon')).toHaveCount(0)
  await expect(other.getByText('pending', { exact: true })).toHaveCount(0)
  await expect(other.getByText('No non-zero payments yet.')).toBeVisible()
})

test('filters monthly household and member spending by category', async ({ page }) => {
  await page.goto('/money')
  const household = page.getByRole('region', { name: 'Monthly spending' })
  await household.getByRole('button', { name: /^Rent/ }).click()
  await expect(household.getByText('Rent · $3,200.00')).toBeVisible()
  await expect(household.getByText('Monthly rent', { exact: true })).toBeVisible()
  await expect(household.getByText('Internet', { exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'View balance for Brandon' }).click()
  const dialog = page.getByRole('dialog', { name: "Brandon's balance" })
  const personal = dialog.getByRole('region', { name: 'Monthly spending' })
  await personal.getByRole('button', { name: /^Rent/ }).click()
  await expect(personal.getByText('Rent · $800.00')).toBeVisible()
  await personal.getByLabel('Spending month').fill('1900-01')
  await expect(personal.getByText('No spending in rent this month.')).toBeVisible()
  await personal.getByRole('button', { name: 'All categories' }).click()
  await expect(personal.getByText('No spending in this month.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('button', { name: 'View balance for Noah' }).click()
  const roommate = page.getByRole('dialog', { name: "Noah's balance" }).getByRole('region', { name: 'Monthly spending' })
  await roommate.getByRole('button', { name: /^Rent/ }).click()
  await expect(roommate.getByText('Rent · $800.00')).toBeVisible()
})
